from sqlalchemy import Boolean, CheckConstraint, Column, Float, ForeignKey, Integer, JSON, String, Table, text

from core.db import metadata


load_advisories = Table('load_advisories', metadata,
    Column('code', String(64), primary_key=True),
    Column('truck', String(160), ForeignKey('truck_racks.code'), nullable=False),
    Column('route', String(160), nullable=False),
    Column('cycle', String(160), nullable=False),
    Column('rms_goal', Float, nullable=False),
    Column('ceiling_kg', Float, nullable=False),
    Column('slope', Float, nullable=False),
    Column('intercept', Float, nullable=True),
    Column('intercept_kg', Float, nullable=True),
    Column('validation_mae', Float, nullable=False),
    Column('candidate_mae', Float, nullable=True),
    Column('baseline_mae', Float, nullable=True),
    Column('old_validation_mae', Float, nullable=True),
    Column('old_mae', Float, nullable=True),
    Column('mae_old', Float, nullable=True),
    Column('mae_improvement', Float, nullable=True),
    Column('mae_delta', Float, nullable=True),
    Column('exclusion_count', Integer, nullable=False),
    Column('evidence_span', String(160), nullable=False),
    Column('holdout_codes', JSON, nullable=True),
    Column('holdout', JSON, nullable=True),
    Column('selected_holdouts', JSON, nullable=True),
    Column('mae_comparison', JSON, nullable=True),
    Column('comparison', JSON, nullable=True),
    Column('fit_credential', String(160), nullable=True),
    Column('fit_token', String(64), nullable=True),
    Column('credential', JSON, nullable=True),
    Column('fit_evidence', JSON, nullable=True),
    Column('evidence', JSON, nullable=True),
    Column('coefficients', JSON, nullable=True),
    Column('model', JSON, nullable=True),
    Column('fit_result', JSON, nullable=True),
    Column('token', String(64), nullable=True, unique=True),
    Column('based_on', String(64), ForeignKey('load_advisories.code'), nullable=True),
    Column('base_code', String(64), nullable=True),
    Column('original_code', String(64), nullable=True),
    Column('parent_code', String(64), nullable=True),
    Column('source_code', String(64), nullable=True),
    Column('replaces', String(64), ForeignKey('load_advisories.code'), nullable=True),
    Column('supersedes', String(64), nullable=True),
    Column('replaced_by', String(64), ForeignKey('load_advisories.code'), nullable=True),
    Column('version', Integer, nullable=False, server_default=text('1')),
    Column('revision', Integer, nullable=False, server_default=text('1')),
    Column('current', Boolean, nullable=False, server_default=text('true')),
    Column('is_current', Boolean, nullable=False, server_default=text('true')),
    Column('active', Boolean, nullable=False, server_default=text('true')),
    Column('status', String(32), nullable=False, server_default='现行'),
    Column('state', String(32), nullable=False, server_default='current'),
    Column('lifecycle', String(32), nullable=False, server_default='current'),
    CheckConstraint('ceiling_kg >= 0'),
    CheckConstraint('slope > 0'),
    CheckConstraint('validation_mae >= 0'),
)
